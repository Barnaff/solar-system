/**
 * Geocentric ecliptic position of the Moon.
 * @returns {{lon:number, lat:number, dist:number}} radians, radians, kilometres
 */
export function moonSpherical(jdTT) {
  const T = (jdTT - J2000) / 36525;
  const T2 = T * T, T3 = T2 * T, T4 = T3 * T;

  const Lp = norm360(218.3164477 + 481267.88123421 * T - 0.0015786 * T2 + T3 / 538841 - T4 / 65194000);
  const D = norm360(297.8501921 + 445267.1114034 * T - 0.0018819 * T2 + T3 / 545868 - T4 / 113065000);
  const M = norm360(357.5291092 + 35999.0502909 * T - 0.0001536 * T2 + T3 / 24490000);
  const Mp = norm360(134.9633964 + 477198.8675055 * T + 0.0087414 * T2 + T3 / 69699 - T4 / 14712000);
  const F = norm360(93.2720950 + 483202.0175233 * T - 0.0036539 * T2 - T3 / 3526000 + T4 / 863310000);

  const A1 = norm360(119.75 + 131.849 * T);
  const A2 = norm360(53.09 + 479264.290 * T);
  const A3 = norm360(313.45 + 481266.484 * T);
  const E = 1 - 0.002516 * T - 0.0000074 * T2;

  let sumL = 0, sumR = 0, sumB = 0;

  for (const [d, m, mp, f, cl, cr] of TERMS_LR) {
    const arg = (d * D + m * M + mp * Mp + f * F) * DEG;
    const ecc = m === 0 ? 1 : Math.abs(m) === 1 ? E : E * E;
    sumL += cl * ecc * Math.sin(arg);
    sumR += cr * ecc * Math.cos(arg);
  }
  for (const [d, m, mp, f, cb] of TERMS_B) {
    const arg = (d * D + m * M + mp * Mp + f * F) * DEG;
    const ecc = m === 0 ? 1 : Math.abs(m) === 1 ? E : E * E;
    sumB += cb * ecc * Math.sin(arg);
  }

  // Additive terms for Venus, Jupiter and the Earth's flattening.
  sumL += 3958 * Math.sin(A1 * DEG) + 1962 * Math.sin((Lp - F) * DEG) + 318 * Math.sin(A2 * DEG);
  sumB += -2235 * Math.sin(Lp * DEG) + 382 * Math.sin(A3 * DEG) +
    175 * Math.sin((A1 - F) * DEG) + 175 * Math.sin((A1 + F) * DEG) +
    127 * Math.sin((Lp - Mp) * DEG) - 115 * Math.sin((Lp + Mp) * DEG);

  return {
    lon: norm360(Lp + sumL / 1e6) * DEG,
    lat: (sumB / 1e6) * DEG,
    dist: 385000.56 + sumR / 1000,
  };
}

/**
 * Geocentric position of the Moon in the ecliptic J2000 frame, in kilometres.
 * The series above yields the equinox of date, so the result is precessed back
 * to J2000 to match the planetary elements.
 */
export function moonGeocentricKm(jdTT) {
  const { lon, lat, dist } = moonSpherical(jdTT);
  return eclipticDateToJ2000(sph(lon, lat, dist), (jdTT - J2000) / 36525);
}
